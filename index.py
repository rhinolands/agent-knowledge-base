"""Build a retrieval index + capability map from a three-bucket knowledge base.

Buckets (by frontmatter `type`):
  - concept    durable "how it works"
  - reference  pointers to authoritative sources
  - log        time-ordered decisions / activity

What it does, stdlib-only (no deps):
  1. Parse each `kb/**/*.md` doc's frontmatter (name / type / description).
  2. LINT — every doc must declare all three fields and a known type,
     and no two docs may share a name; a violation exits non-zero so
     this can gate CI.
  3. CHUNK each body into overlapping windows tagged with the doc's metadata,
     ready to embed into a vector store for RAG.
  4. EMIT  index.json (chunks + doc metadata) and capability-map.md
     (human/agent overview grouped by bucket).

Run:  python index.py [--kb kb] [--chunk-size 800] [--overlap 100]
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

KNOWN_TYPES = {"concept", "reference", "log"}
REQUIRED_FIELDS = ("name", "type", "description")


def parse_frontmatter(text: str) -> tuple[dict[str, str], str]:
    """Split a `--- key: value ---` frontmatter block from the body.

    Minimal on purpose: flat `key: value` pairs only, no YAML dependency.
    Returns (metadata, body). Missing/!malformed frontmatter -> ({}, text).
    """
    if not text.startswith("---"):
        return {}, text
    parts = text.split("---", 2)
    if len(parts) < 3:
        return {}, text
    meta: dict[str, str] = {}
    for line in parts[1].strip().splitlines():
        if ":" in line:
            key, _, value = line.partition(":")
            meta[key.strip()] = value.strip()
    return meta, parts[2].lstrip("\n")


def chunk(body: str, size: int, overlap: int) -> list[str]:
    """Sliding-window chunks over the body. Overlap preserves context across cuts."""
    words = body.split()
    if not words:
        return []
    chunks, step = [], max(1, size - overlap)
    # Approximate char budget by words (~5 chars/word incl. space).
    words_per_chunk = max(1, size // 5)
    words_step = max(1, step // 5)
    for start in range(0, len(words), words_step):
        window = words[start : start + words_per_chunk]
        if window:
            chunks.append(" ".join(window))
        if start + words_per_chunk >= len(words):
            break
    return chunks


def build(kb_dir: Path, size: int, overlap: int) -> tuple[list[dict], list[str]]:
    """Return (records, errors). One record per chunk; errors gate the lint."""
    records: list[dict] = []
    errors: list[str] = []
    seen: dict[str, str] = {}  # name -> first path, so chunk ids stay unique
    for path in sorted(kb_dir.rglob("*.md")):
        meta, body = parse_frontmatter(path.read_text(encoding="utf-8"))
        rel = path.relative_to(kb_dir).as_posix()
        missing = [f for f in REQUIRED_FIELDS if not meta.get(f)]
        if missing:
            errors.append(f"{rel}: missing frontmatter {missing}")
            continue
        if meta["type"] not in KNOWN_TYPES:
            errors.append(
                f"{rel}: unknown type {meta['type']!r} (expected {KNOWN_TYPES})"
            )
            continue
        if meta["name"] in seen:
            errors.append(
                f"{rel}: duplicate name {meta['name']!r} (also in {seen[meta['name']]})"
            )
            continue
        seen[meta["name"]] = rel
        for i, piece in enumerate(chunk(body, size, overlap)):
            records.append(
                {
                    "id": f"{meta['name']}#{i}",
                    "name": meta["name"],
                    "type": meta["type"],
                    "description": meta["description"],
                    "path": rel,
                    "chunk": i,
                    "text": piece,
                }
            )
    return records, errors


def capability_map(records: list[dict]) -> str:
    """Markdown overview grouped by bucket — the agent's table of contents."""
    by_type: dict[str, dict[str, str]] = {t: {} for t in KNOWN_TYPES}
    for r in records:
        by_type[r["type"]][r["name"]] = r["description"]
    out = [
        "# Capability map",
        "",
        "_Generated by `index.py` — do not edit by hand._",
        "",
    ]
    for t in ("concept", "reference", "log"):
        docs = by_type[t]
        if not docs:
            continue
        out.append(f"## {t} ({len(docs)})")
        for name, desc in sorted(docs.items()):
            out.append(f"- **{name}** — {desc}")
        out.append("")
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--kb", default="kb", type=Path)
    ap.add_argument(
        "--chunk-size", type=int, default=800, help="approx chars per chunk"
    )
    ap.add_argument("--overlap", type=int, default=100, help="approx char overlap")
    args = ap.parse_args()

    if not args.kb.is_dir():
        print(f"error: kb dir {args.kb!r} not found", file=sys.stderr)
        return 2

    records, errors = build(args.kb, args.chunk_size, args.overlap)
    if errors:
        print("LINT FAILED:", file=sys.stderr)
        for e in errors:
            print(f"  - {e}", file=sys.stderr)
        return 1

    Path("index.json").write_text(json.dumps(records, indent=2), encoding="utf-8")
    Path("capability-map.md").write_text(capability_map(records), encoding="utf-8")

    docs = {r["name"] for r in records}
    print(f"ok — {len(docs)} docs, {len(records)} chunks")
    print("wrote index.json, capability-map.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
